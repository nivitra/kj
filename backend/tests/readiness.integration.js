// Runs only against an explicitly named disposable database; never production.
const assert = require('node:assert/strict');
if (!process.env.DATABASE_URL?.includes('sj_release_rehearsal')) throw new Error('Use the isolated sj_release_rehearsal database');
const { prisma: db } = require('../src/config/prisma');
const { createSentInvoice } = require('../src/services/billing/issueAndNotify');
const { recordPayment, voidPayment } = require('../src/services/billing/paymentService');
const { calculateQuote } = require('../src/services/billing/quotePricing');
const { acceptQuote, convertQuote } = require('../src/services/billing/quoteLifecycle');
const { applyInvoiceCoupon } = require('../src/services/billing/couponService');
const { setSelected, submitSelection, startEditing } = require('../src/services/selectionWorkflow');
const { requestRawDump } = require('../src/services/rawDump');
const { reportPayment, reviewPayment } = require('../src/services/billing/paymentClaims');
async function run() {
 const studio = await db.studio.create({ data: { name:'Release test', email:`release-${Date.now()}@example.invalid` } });
 const studioId = studio.id;
 const admin = await db.adminUser.create({data:{studioId,email:`admin-${studioId}@example.invalid`,name:'Test',passwordHash:'disabled',role:'OWNER'}});
 const customer = await db.customer.create({data:{studioId,name:'Test customer'}});
 const customerId = customer.id;
 const invoice = async (amount, cid=customerId) => createSentInvoice({studioId,customerId:cid,lines:[{description:'Service',quantity:1,unitAmount:amount,lineTotal:amount}],fiftyFifty:true});
 const inv = await invoice(60000);
 const pay = (amount,key,kind='PAYMENT') => recordPayment({studioId,invoiceId:inv.id,admin,body:{amount,idempotencyKey:key,kind}});
 const key=`retry:${inv.id}`;
 await Promise.all([pay(20000,key),pay(20000,key)]);
 await pay(15000,`second:${inv.id}`);
 let row=await db.invoice.findUnique({where:{id:inv.id}});
 assert.equal(Number(row.amountPaid),35000); assert.equal(Number(row.cachedOutstanding),25000);
 await assert.rejects(pay(19000,key));
 await pay(5000,`refund:${inv.id}`,'REFUND');
 row=await db.invoice.findUnique({where:{id:inv.id}});assert.equal(Number(row.amountPaid),30000);
 await assert.rejects(recordPayment({studioId,invoiceId:inv.id,admin:{role:'STAFF'},body:{amount:1,_skipRoleCheck:true}}));
 console.log('PASS payment concurrency, refund, idempotency, role enforcement');
 const sp=await db.servicePackage.create({data:{studioId,title:'Test package',price:1000,includedPhotos:20,pricePerExtraPhoto:350}});
 const catalog={options:[{id:sp.id,servicePackageId:sp.id,title:'A',price:1000},{id:'alternative',title:'B',price:2000}],addOns:[]};
 const pricing=calculateQuote(catalog,{optionIds:[sp.id,'alternative']},18);
 assert.equal(pricing.alternatives[0].total,1180);assert.equal(pricing.alternatives[1].total,2360);
 const q=await db.quote.create({data:{studioId,customerId,status:'SENT',pricingSnapshot:pricing}});
 await acceptQuote({studioId,quoteId:q.id,customerId,optionId:sp.id,actor:customerId});
 const converted=await Promise.all([convertQuote({studioId,quoteId:q.id,admin}),convertQuote({studioId,quoteId:q.id,admin})]);
 assert.equal(converted[0].invoiceId,converted[1].invoiceId);
 row=await db.invoice.findUnique({where:{id:converted[0].invoiceId}});assert.equal(Number(row.totalAmount),1180);assert.equal(Number(row.taxAmount),180);
 console.log('PASS alternatives, exact tax, concurrent one-time quote conversion');
 const c2=await db.customer.create({data:{studioId,name:'Second customer'}});
 const i1=await invoice(1000),i2=await invoice(1000,c2.id);
 await db.coupon.create({data:{studioId,code:'LAST',discountType:'FIXED',discountValue:100,maxRedemptions:1}});
 const coupons=await Promise.allSettled([applyInvoiceCoupon({studioId,customerId,invoiceId:i1.id,code:'LAST'}),applyInvoiceCoupon({studioId,customerId:c2.id,invoiceId:i2.id,code:'LAST'})]);
 assert.equal(coupons.filter(x=>x.status==='fulfilled').length,1);
 assert.equal(await db.couponRedemption.count({where:{studioId}}),1);
 console.log('PASS last coupon concurrency');
 const gallery=await db.eventGallery.create({data:{studioId,name:'Selection test',status:'PUBLISHED',selectionLimit:20,extraPhotoPrice:350,bulkRawEnabled:true,bulkRawPrice:2000}});
 const galleryId=gallery.id;
 const grant=await db.accessGrant.create({data:{customerId,galleryId}});
 const args={studioId,customerId,galleryId};
 const photos=[];
 for(let n=0;n<26;n++)photos.push(await db.photo.create({data:{galleryId,originalKey:`test/${galleryId}/originals/${n}.jpg`,filename:`${n}.jpg`,fileSize:100,mimeType:'image/jpeg',isVisibleToCustomers:true}}));
 for(const p of photos.slice(0,23))await setSelected({...args,photoId:p.id,selected:true});
 const subs=await Promise.all([submitSelection(args),submitSelection(args)]);
 assert.equal(subs[0].billing.invoiceId,subs[1].billing.invoiceId);assert.equal(subs[0].billing.overageTotal,1050);
 let selection=await db.selection.findUnique({where:{customerId_galleryId:{customerId,galleryId}}});
 await recordPayment({studioId,invoiceId:subs[0].billing.invoiceId,admin,body:{amount:1050,idempotencyKey:`extras:${galleryId}`}});
 await setSelected({...args,photoId:photos[22].id,selected:false});
 await submitSelection(args);
 row=await db.invoice.findUnique({where:{id:subs[0].billing.invoiceId}});assert.equal(Number(row.totalAmount),700);assert.equal(Number(row.amountPaid),1050);assert.match(row.notes,/Credit/);
 await startEditing({studioId,selectionId:selection.id,admin});
 await assert.rejects(setSelected({...args,photoId:photos[0].id,selected:false}));
 for(const p of photos.slice(23,25))await setSelected({...args,photoId:p.id,selected:true});
 const extra=await submitSelection(args);assert.equal(extra.billing.overageTotal,700);assert.notEqual(extra.billing.invoiceId,subs[0].billing.invoiceId);
 console.log('PASS continuous selection, revisions, credit preservation, editing lock, incremental extras');
 const manyGallery=await db.eventGallery.create({data:{studioId,name:'Unlimited picking',status:'PUBLISHED',selectionLimit:100,extraPhotoPrice:999}});
 await db.accessGrant.create({data:{customerId,galleryId:manyGallery.id,selectionLimit:20,extraPhotoPrice:25}});
 const manyArgs={studioId,customerId,galleryId:manyGallery.id};
 const photoData=Array.from({length:125},(_,n)=>({galleryId:manyGallery.id,originalKey:`test/${manyGallery.id}/${n}.jpg`,filename:`${n}.jpg`,fileSize:1,mimeType:'image/jpeg',isVisibleToCustomers:true}));
 await db.photo.createMany({data:photoData});
 const manyPhotos=await db.photo.findMany({where:{galleryId:manyGallery.id}});
 await db.favorite.createMany({data:manyPhotos.slice(0,124).map(p=>({customerId,photoId:p.id}))});
 const picked=await setSelected({...manyArgs,photoId:manyPhotos[124].id,selected:true});
 assert.equal(picked.count,125);assert.equal(picked.estimate.includedPhotos,20);assert.equal(picked.estimate.extraCount,105);assert.equal(picked.estimate.overageTotal,2625);
 const manySubmit=await submitSelection(manyArgs);assert.equal(manySubmit.billing.overageTotal,2625);
 assert.equal(await db.selectionItem.count({where:{selection:{galleryId:manyGallery.id}}}),125);
 console.log('PASS 125 photos selected and submitted without cap; customer allowance 20 and rate 25 override gallery 100 and 999');
 const legacyGallery=await db.eventGallery.create({data:{studioId,name:'Legacy shared invoice',status:'PUBLISHED',selectionLimit:0,extraPhotoPrice:25}});
 await db.accessGrant.create({data:{customerId,galleryId:legacyGallery.id}});
 const legacyArgs={studioId,customerId,galleryId:legacyGallery.id};
 const legacyPhotos=[];for(let n=0;n<3;n++)legacyPhotos.push(await db.photo.create({data:{galleryId:legacyGallery.id,originalKey:`test/${legacyGallery.id}/${n}.jpg`,filename:`${n}.jpg`,fileSize:1,mimeType:'image/jpeg',isVisibleToCustomers:true}}));
 const sharedInvoice=await invoice(900);
 await db.selection.create({data:{customerId,galleryId:legacyGallery.id,status:'SUBMITTED',deliveryStatus:'BILLED',overageInvoiceId:sharedInvoice.id,overageAmount:50,extraUnitPrice:25,includedLimit:0,submittedAt:new Date(),items:{create:legacyPhotos.slice(0,2).map(p=>({photoId:p.id,deliveryType:'EDITED'}))}}});
 const legacySql=require('node:fs').readFileSync(require('node:path').join(__dirname,'../prisma/release-migrations/20260916_zlegacy_selections.sql'),'utf8');
 await db.$transaction(async tx=>{for(const sql of legacySql.split(';').map(s=>s.trim()).filter(Boolean))await tx.$executeRawUnsafe(sql);});
 await setSelected({...legacyArgs,photoId:legacyPhotos[2].id,selected:true});
 const legacyExtra=await submitSelection(legacyArgs);assert.equal(legacyExtra.billing.overageTotal,25);assert.notEqual(legacyExtra.billing.invoiceId,sharedInvoice.id);
 assert.equal(Number((await db.invoice.findUnique({where:{id:sharedInvoice.id}})).totalAmount),900);
 console.log('PASS legacy shared invoice remains unchanged and only new extras are billed');
 const raw=await Promise.all([requestRawDump({studioId,customerId,gallery,grant}),requestRawDump({studioId,customerId,gallery,grant})]);assert.equal(raw[0].invoice.id,raw[1].invoice.id);
 const claim=await reportPayment({studioId,customerId,invoiceId:raw[0].invoice.id,amount:2000,reference:`UTR-${galleryId}`});
 assert.equal((await db.accessGrant.findUnique({where:{id:grant.id}})).rawAccess,false);
 await Promise.all([reviewPayment({studioId,claimId:claim.id,admin,approve:true}),reviewPayment({studioId,claimId:claim.id,admin,approve:true})]);
 let paidGrant=await db.accessGrant.findUnique({where:{id:grant.id}});assert.equal(paidGrant.rawAccess,true);
 assert.equal(await db.invoicePayment.count({where:{invoiceId:raw[0].invoice.id}}),1);
 const approved=await db.paymentClaim.findUnique({where:{id:claim.id}});
 await voidPayment({studioId,invoiceId:raw[0].invoice.id,paymentId:approved.paymentId,admin,reason:'Test reversal'});
 paidGrant=await db.accessGrant.findUnique({where:{id:grant.id}});assert.equal(paidGrant.rawAccess,false);
 console.log('PASS raw purchase retry, pending claim, confirmation once, revoked unpaid access');
 const invoices=await db.invoice.findMany({where:{customerId,status:{notIn:['VOID','DRAFT']},kind:'INVOICE'}});
 const rollup=await db.customer.findUnique({where:{id:customerId}});
 assert.equal(Number(rollup.paymentAmountPaid),invoices.reduce((s,x)=>s+Number(x.amountPaid),0));
 assert.equal(Number(rollup.paymentTotalDue),invoices.reduce((s,x)=>s+Number(x.totalAmount),0));
 console.log('PASS customer aggregate across all workflows');
 const legacy=await invoice(100);
 await db.invoice.update({where:{id:legacy.id},data:{amountPaid:40}});
 await recordPayment({studioId,invoiceId:legacy.id,admin,body:{amount:10,idempotencyKey:`legacy:${legacy.id}`}});
 assert.equal(Number((await db.invoice.findUnique({where:{id:legacy.id}})).amountPaid),50);
 const {estimateSelection}=require('../src/services/pricing');
 const free=await estimateSelection({studioId,selectionLimit:0,extraPhotoPrice:0},3,null);
 assert.equal(free.pricingReady,true);assert.equal(free.overageTotal,0);assert.equal(free.extraCount,3);
 const missing=await estimateSelection({studioId},3,null);assert.equal(missing.pricingReady,false);
 const frozen=await db.eventGallery.create({data:{studioId,name:'Agreed prices',status:'PUBLISHED',pricingSnapshot:{id:sp.id,title:'Agreed',includedPhotos:20,pricePerExtraPhoto:350}}});
 await db.servicePackage.update({where:{id:sp.id},data:{pricePerExtraPhoto:900,includedPhotos:5}});
 const frozenPrice=await estimateSelection(frozen,23,customerId);assert.equal(frozenPrice.overageTotal,1050);
 console.log('PASS legacy paid balance, zero versus missing pricing, agreed price snapshot');

}
run().then(()=>console.log('All release integration scenarios passed')).catch(e=>{console.error(e);process.exitCode=1}).finally(()=>db.$disconnect());
